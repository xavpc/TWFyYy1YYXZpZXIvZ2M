import { ApiProperty } from '@nestjs/swagger';
import { RouteCoordinates, Route, Prisma } from '@prisma/client';

type RouteCoordinatesWithRoute = Prisma.RouteCoordinatesGetPayload<{ include: { route: true } }>;

export class RouteCoordinatesResponse {
  @ApiProperty({
    description: 'The unique ID of the route coordinates',
    example: '123e4567-e89b-12d3-a456-426614174000',
  })
  route_coordinates_id: string;

  @ApiProperty({
    description: 'The latitude of the route coordinates',
    example: 35.6895,
  })
  latitude: number;

  @ApiProperty({
    description: 'The longitude of the route coordinates',
    example: 139.6917,
  })
  longitude: number;

  @ApiProperty({
    description: 'A unique sequence number for the route coordinates, to know the precedence of points',
    example: 1,
  })
  sequence: number;

  @ApiProperty({
    description: 'A boolean to know if the intance of route coordinate is created by user or generated by gmaps API',
    example: true,
  })
  is_user_point: boolean;

  @ApiProperty({
    description: 'The route associated with these coordinates',
    type: 'object',
    example: {
      route_id: 'e5a53ba6-deda-11ef-9da2-54ee75718d0f',
      route_name: 'Route D',
      center_latitude: 35.6895,
      center_longitude: 139.6917
    },
  })
  route: Route;

  constructor(routeCoordinates: RouteCoordinatesWithRoute) {
    this.route_coordinates_id = routeCoordinates.route_coordinates_id;
    this.latitude = Number(routeCoordinates.latitude);
    this.longitude = Number(routeCoordinates.longitude);
    this.sequence = routeCoordinates.sequence;
    this.is_user_point = routeCoordinates.is_user_point;
    this.route = routeCoordinates.route;
  }
}

export class RouteCoordinatesListResponse {
  @ApiProperty({
    description: 'List of route coordinates',
    type: [RouteCoordinatesResponse],
  })
  data: RouteCoordinatesResponse[];

  @ApiProperty({
    description: 'Total number of route coordinates available',
    example: 5,
  })
  total: number;

  constructor(routeCoordinates: RouteCoordinates[]) {
    this.data = routeCoordinates.map(
      (coord) => new RouteCoordinatesResponse(coord),
    );
    this.total = routeCoordinates.length;
  }
}

export class RouteCoordinatesErrorResponse {
  @ApiProperty({
    description: 'Error code',
    example: 'NOT_FOUND',
  })
  error_code: string;

  @ApiProperty({
    description: 'Error message',
    example: 'Route Coordinates not found',
  })
  message: string;

  constructor(errorCode: string, message: string) {
    this.error_code = errorCode;
    this.message = message;
  }
}